#!/usr/bin/env python3
"""Write the built-in Tokyo Night fallback colours and the plugin's Tokens.js.

Colours have one source: herdr_attention/herdr_theme.py. At run time the server reads the Omarchy
theme live and sends the colour tokens as /theme.css (web) and view.theme.tokens (bar panel). This
script writes the fallback that is used when those are not there, from herdr_theme.TOKYO_NIGHT:

* the palette block (/* palette:start */ .. /* palette:end */) in herdr_attention/web/style.css,
* the theme-color meta in herdr_attention/web/index.html,
* plugin/alexvdb.herdr-attention/Tokens.js (fallback colours, plus radii, the 4 px spacing steps and
  the type sizes from the style.css token block).

    python3 scripts/gen_tokens.py           # write the three files
    python3 scripts/gen_tokens.py --check   # exit 1 if any of them is out of date
"""

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
from herdr_attention import herdr_theme  # noqa: E402

CSS = REPO / "herdr_attention" / "web" / "style.css"
HTML = REPO / "herdr_attention" / "web" / "index.html"
OUT = REPO / "plugin" / "alexvdb.herdr-attention" / "Tokens.js"
META = re.compile(r'<meta name="theme-color" content="[^"]*">')


def block(css: str) -> str:
    start = css.index("/* tokens:start")
    return css[start:css.index("/* tokens:end */", start)]


def decls(text: str) -> dict:
    return {k: v.strip() for k, v in re.findall(r"--([a-z0-9-]+)\s*:\s*([^;]+);", text)}


def camel(key: str) -> str:
    return re.sub(r"-([a-z])", lambda m: m.group(1).upper(), key)


def tokens(css: str) -> dict:
    """Fallback colours (from herdr_theme) and shape, space and type (from the style.css token block)."""
    d = decls(block(css))
    px = lambda v: (lambda f: int(f) if f.is_integer() else f)(float(v.removesuffix("px")))
    type_size = {name: round(float(re.search(r"\s([\d.]+)px/", d[f"t-{name}"]).group(1)) + 1e-9)
                 for name in ("micro", "small", "body", "title", "head")}
    return {
        "fallback": {camel(k): v for k, v in herdr_theme.fallback_theme()["tokens"].items()},
        "radius": {k[2:]: px(v) for k, v in d.items() if k.startswith("r-") and k != "r-full"},
        "space": {k[2:]: px(v) for k, v in d.items() if re.fullmatch(r"s-\d", k)},
        "type": type_size,
    }


def palette_block() -> str:
    theme = herdr_theme.fallback_theme()
    items = [f"--{k}: {v};" for k, v in theme["tokens"].items()]
    rows = ["  " + " ".join(items[i:i + 6]) for i in range(0, len(items), 6)]
    rows.append(f"  --tint: {theme['tint']}; color-scheme: {theme['mode']};")
    return "  /* palette:start */\n" + "\n".join(rows) + "\n  /* palette:end */"


def render_css(css: str) -> str:
    return re.sub(r"  /\* palette:start \*/.*?/\* palette:end \*/", lambda _: palette_block(), css, count=1, flags=re.S)


def render_html(html: str) -> str:
    bg = herdr_theme.fallback_theme()["tokens"]["bg"]
    return META.sub(f'<meta name="theme-color" content="{bg}">', html, count=1)


def render_js(t: dict) -> str:
    dump = lambda x: json.dumps(x, indent=2, sort_keys=True)
    return f""".pragma library
// GENERATED by scripts/gen_tokens.py from herdr_attention/herdr_theme.py and the token block in
// herdr_attention/web/style.css. Do not edit; run the script. tests/test_tokens_js.py fails when this drifts.

// Colours come live from the server (view.theme.tokens: the Omarchy theme's palette, with Herdr's
// status colours). This built-in Tokyo Night set is only the fallback.
var fallback = {dump(t["fallback"])}

var radius = {dump(t["radius"])}

// 4 px grid: space["1"] = 4 ... space["8"] = 32
var space = {dump(t["space"])}

// pixel sizes of the five text styles (rounded to whole pixels for QML)
var type = {dump(t["type"])}

// Colour tokens for a view: the server's live theme, each missing value from the fallback.
function palette(view) {{
  var live = view && view.theme && view.theme.tokens ? view.theme.tokens : {{}}
  var p = {{}}
  for (var key in fallback) {{
    var css = key.replace(/[A-Z]/g, function (c) {{ return "-" + c.toLowerCase() }})
    var value = live[css]
    p[key] = typeof value === "string" && /^#[0-9a-fA-F]{{6}}$/.test(value) ? value : fallback[key]
  }}
  return p
}}

// Dashboard state -> colour (Herdr's status colours). Red ("needs") only for waiting on you.
function stateColor(p, state) {{
  if (state === "needs_you") return p.needs
  if (state === "working") return p.working
  if (state === "done") return p.done
  if (state === "waiting") return p.waiting
  if (state === "parked") return p.parked
  if (state === "caution" || state === "stall" || state === "out_of_quota") return p.caution
  return p.unknown
}}
"""


def main() -> int:
    css = CSS.read_text()
    outputs = {CSS: render_css(css), HTML: render_html(HTML.read_text()), OUT: render_js(tokens(css))}
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    if "--check" in sys.argv[1:]:
        for path in stale:
            print(f"{path.relative_to(REPO)} is out of date: run scripts/gen_tokens.py", file=sys.stderr)
        return 1 if stale else 0
    for path in stale:
        path.write_text(outputs[path])
        print(f"wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
