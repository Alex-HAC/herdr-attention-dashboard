"""Shared transport and navigation definitions; browser copy is checked in CI."""
from __future__ import annotations

import ipaddress
import json
from pathlib import Path
from urllib.parse import quote

CONTRACT = json.loads(Path(__file__).with_name('ui_contract.json').read_text())
API = CONTRACT['api']
FEATURES = CONTRACT['features']


def hash_path(name: str, identity: str | int = '') -> str:
    return CONTRACT['hashes'][name].replace('{id}', quote(str(identity), safe=''))


def api_path(name: str, identity: str | int) -> str:
    return API[name].replace('{id}', quote(str(identity), safe=''))


def route_id(name: str, path: str) -> str | None:
    import re
    pattern = re.escape(API[name]).replace(r'\{id\}', '([^/]+)')
    match = re.fullmatch(pattern, path)
    return match.group(1) if match else None


def listener_address(settings, surface: str) -> tuple[str, int]:
    host = settings.get(f'{surface}.bind')
    port = int(settings.get(f'{surface}.port'))
    if not 0 <= port <= 65535:
        raise ValueError('invalid listener port')
    # IPv4 HTTPServer: accept numeric IPv4 loopback addresses only. Never
    # resolve a hostname or trust forwarded headers to establish capability.
    if surface == 'desktop':
        address = ipaddress.IPv4Address(host)
        if not address.is_loopback:
            raise ValueError('desktop.bind must be an IPv4 loopback address')
    return host, port


def desktop_url(settings) -> str:
    host, port = listener_address(settings, 'desktop')
    return f'http://{host}:{port}'


def navigation_hash(target: object) -> str | None:
    """Return target when it is a route the desktop wrapper may hand over."""
    import re
    if not isinstance(target, str):
        return None
    for name in CONTRACT['desktop']['navigation']:
        template = CONTRACT['hashes'][name]
        # Notification ids are numbers; the terminal route (v0.9.8) takes an agent identity.
        ident = r'[A-Za-z0-9._~%-]{1,200}' if name == 'terminal' else '[0-9]+'
        pattern = re.escape(template).replace(r'\{id\}', ident)
        if re.fullmatch(pattern, target):
            return target
    return None


def navigation_names() -> list[str]:
    """Desktop navigation routes that take no id (the wrapper's --route values)."""
    return [name for name in CONTRACT['desktop']['navigation'] if '{id}' not in CONTRACT['hashes'][name]]


def browser_source() -> str:
    from .notify_tiers import ACTION_LABELS
    public = {k: CONTRACT[k] for k in ('api', 'hashes', 'views', 'features', 'desktop', 'watch_closely', 'easy_reply', 'ask_items', 'question_preview', 'arrange', 'quotas', 'account_icons', 'cleanup', 'runtime', 'files')}
    public['labels'] = ACTION_LABELS
    return '// Generated by scripts/gen_ui_contract.py; do not edit.\nconst UI = ' + json.dumps(public, ensure_ascii=False, indent=2) + ';\n'


PLUGIN_CONTRACT = 'plugin/alexvdb.herdr-attention/Contract.js'


def plugin_source() -> str:
    """The bar panel's copy: section ids and labels for Arrange, the panel's own labels, and the
    account icon glyphs and colour names (the same marks the page draws)."""
    public = {k: CONTRACT[k] for k in ('arrange', 'panel', 'account_icons')}
    return ('.pragma library\n// Generated by scripts/gen_ui_contract.py from herdr_attention/ui_contract.json; do not edit.\n'
            'var UI = ' + json.dumps(public, ensure_ascii=False, indent=2) + '\n')


def definition_errors(root: Path | None = None, sources: dict[str, str] | None = None) -> list[str]:
    """Catch stale generated definitions and new copies in shipping consumers.

    Tests may substitute source text to prove the check detects a regression.
    Comments/docs and test fixtures are intentionally outside this boundary.
    """
    import ast
    import io
    import re
    import tokenize
    root = root or Path(__file__).resolve().parents[1]
    errors = []
    generated = root / 'herdr_attention/web/ui-contract.js'
    if generated.read_text() != browser_source():
        errors.append('generated browser contract is stale')
    plugin = root / PLUGIN_CONTRACT
    if not plugin.exists() or plugin.read_text() != plugin_source():
        errors.append('generated panel contract is stale')
    files = [*root.glob('herdr_attention/*.py'), *root.glob('herdr_attention/web/*.js'),
             *root.glob('plugin/alexvdb.herdr-attention/*.qml'),
             *root.glob('plugin/alexvdb.herdr-attention/*.js'), root / 'scripts/install.sh']
    from .notify_tiers import ACTION_LABELS
    from .config import DEFAULTS
    for surface, defaults in CONTRACT['listeners'].items():
        if any(DEFAULTS[surface][key] != value for key, value in defaults.items()):
            errors.append(f'{surface} defaults differ from the contract')
    from .focus import FocusTarget, HerdrFocus
    target = FocusTarget('test', 'pane', 'name', 'tab', 'workspace')
    if {method for method, _ in target.fallback_steps()} != HerdrFocus.ALLOWED_METHODS:
        errors.append('focus fallback sequence differs from the write allowlist')
    copies = set(CONTRACT['api'].values()) | set(CONTRACT['hashes'].values())
    copies |= {CONTRACT['desktop']['title'], CONTRACT['desktop']['class']}
    ports = {str(value['port']) for value in CONTRACT['listeners'].values()}
    for path in files:
        relative = str(path.relative_to(root))
        if relative in ('herdr_attention/ui_contract.py', 'herdr_attention/web/ui-contract.js', PLUGIN_CONTRACT):
            continue
        content = (sources or {}).get(relative, path.read_text())
        if path.suffix == '.py':
            tree = ast.parse(content)
            if any(isinstance(node, ast.Dict) and any(isinstance(key, ast.Constant)
                   and key.value == FEATURES['desktop_focus'] for key in node.keys) for node in ast.walk(tree)):
                errors.append(f'{relative}: copied desktop feature definition')
            tokens = list(tokenize.generate_tokens(io.StringIO(content).readline))
            literals = [token.string for token in tokens if token.type == tokenize.STRING
                        and not token.string.startswith(('"""', "'''"))]
            numbers = [token.string for token in tokens if token.type == tokenize.NUMBER]
        else:
            feature = re.escape(FEATURES['desktop_focus'])
            if re.search(r'(?<!UI)\.features(?:\?\.|\.)' + feature + r'\b|\b' + feature + r'\s*:', content):
                errors.append(f'{relative}: copied desktop feature definition')
            # Consume comments as well as strings so comment examples do not
            # look like executable duplicate definitions.
            tokens = re.findall(r'''//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|`(?:\\.|[^`\\])*`''', content)
            literals = [token for token in tokens if not token.startswith(('//', '/*'))]
            numbers = re.findall(r'\b\d+\b', content)
        for token in literals:
            value = token.lstrip('frbuFRBU')[1:-1]
            if value in copies or re.match(r'^/api/[^?]+', value) or value.startswith(('#/a/', '#/n', '#/g/')):
                errors.append(f'{relative}: copied route or desktop definition {value!r}')
            if value in ACTION_LABELS.values() and path.name != 'notify_tiers.py':
                errors.append(f'{relative}: copied action label {value!r}')
            if value in HerdrFocus.ALLOWED_METHODS and path.name != 'focus.py':
                errors.append(f'{relative}: copied focus command {value!r}')
        for port in ports:
            if port in numbers:
                errors.append(f'{relative}: copied listener port {port}')
    return errors
